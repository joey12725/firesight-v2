// Regenerates profile.schema.json from the Rust types and profile.d.ts from the schema.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const root = resolve(web, '..');
const out = resolve(web, 'src/engine');

const schemaText = execFileSync('cargo', ['run', '-q', '-p', 'firesight-cli', '--', 'schema'], {
  cwd: root,
  encoding: 'utf8',
  maxBuffer: 64 * 1024 * 1024,
});
const schema = JSON.parse(schemaText);
writeFileSync(resolve(out, 'profile.schema.json'), JSON.stringify(schema, null, 2) + '\n');

const banner =
  '/* Generated by `npm run schema` from crates/firesight-core/src/model. Do not edit. */\n/* eslint-disable */';
const dts = await compile(schema, 'Profile', {
  bannerComment: banner,
  additionalProperties: false,
  style: { singleQuote: true, printWidth: 100 },
});
writeFileSync(resolve(out, 'profile.d.ts'), dts);
console.log(`schema: ${schemaText.length} bytes, types: ${dts.length} bytes`);
